-- Reports: additive post_id
ALTER TABLE course_discussion_reports
    ADD COLUMN IF NOT EXISTS post_id bigint;

UPDATE course_discussion_reports r
SET post_id = m.post_id
FROM course_discussion_post_id_map m
WHERE r.post_id IS NULL
  AND (
    (m.legacy_kind = 'THREAD' AND upper(r.target_type::text) LIKE '%THREAD%')
    OR (m.legacy_kind = 'REPLY' AND upper(r.target_type::text) LIKE '%REPLY%')
  )
  AND m.legacy_id = r.target_id;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_cdrep_post') THEN
        ALTER TABLE course_discussion_reports
            ADD CONSTRAINT fk_cdrep_post FOREIGN KEY (post_id) REFERENCES course_discussion_posts(id);
    END IF;
END $$;

-- Reconciliation
DO $$
DECLARE
    legacy_t bigint; posts_t bigint;
    legacy_r bigint; posts_r bigint;
    unmapped_react bigint;
    unmapped_rep bigint;
BEGIN
    SELECT count(*) INTO legacy_t FROM course_discussion_threads;
    SELECT count(*) INTO posts_t FROM course_discussion_posts WHERE post_type = 'THREAD';
    IF legacy_t <> posts_t THEN
        RAISE EXCEPTION 'Slice4 A failed: threads legacy=% posts=%', legacy_t, posts_t;
    END IF;

    SELECT count(*) INTO legacy_r FROM course_discussion_replies;
    SELECT count(*) INTO posts_r FROM course_discussion_posts WHERE post_type = 'REPLY';
    IF legacy_r <> posts_r THEN
        RAISE EXCEPTION 'Slice4 B failed: replies legacy=% posts=%', legacy_r, posts_r;
    END IF;

    SELECT count(*) INTO unmapped_react FROM course_discussion_reactions WHERE post_id IS NULL;
    IF unmapped_react <> 0 THEN
        RAISE EXCEPTION 'Slice4 C failed: reactions without post_id=%', unmapped_react;
    END IF;

    SELECT count(*) INTO unmapped_rep FROM course_discussion_reports WHERE post_id IS NULL;
    IF unmapped_rep <> 0 THEN
        RAISE EXCEPTION 'Slice4 D failed: reports without post_id=%', unmapped_rep;
    END IF;
END $$;
