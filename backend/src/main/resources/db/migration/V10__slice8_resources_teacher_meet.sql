    JOIN users u ON u.id = p.teacher_id
    WHERE p.record_type = 'teacher_professional_profiles'
      AND u.teacher_public_profile = COALESCE(p.public_profile, false);
    IF expected <> actual THEN
        RAISE EXCEPTION 'Slice 8 teacher profile reconciliation failed: expected %, got %', expected, actual;
    END IF;

    IF (SELECT count(*) FROM teacher_credentials) <>
       (SELECT count(*) FROM user_auxiliary_records WHERE record_type = 'teacher_credentials') OR
       (SELECT count(*) FROM teacher_google_meet_connections) <>
