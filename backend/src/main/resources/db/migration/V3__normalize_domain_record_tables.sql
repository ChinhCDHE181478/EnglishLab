CREATE TABLE vocabulary_progress (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES users(id),
    course_id bigint NOT NULL REFERENCES online_courses(id),
    term_key varchar(220) NOT NULL,
    vocabulary_status varchar(30) NOT NULL,
    starred boolean NOT NULL,
    last_reviewed_at timestamp,
    review_count integer NOT NULL DEFAULT 0,
    correct_count integer NOT NULL DEFAULT 0,
    incorrect_count integer NOT NULL DEFAULT 0,
    last_result_correct boolean,
    created_at timestamp,
    updated_at timestamp,
    CONSTRAINT uk_vocabulary_progress_term UNIQUE (student_id, course_id, term_key),
    CONSTRAINT ck_vocabulary_progress_counts CHECK (review_count >= 0 AND correct_count >= 0 AND incorrect_count >= 0)
);
INSERT INTO vocabulary_progress
SELECT id, student_id, course_id, term_key, vocabulary_status, starred,
       last_reviewed_at, COALESCE(review_count, 0), COALESCE(correct_count, 0),
       COALESCE(incorrect_count, 0), last_result_correct, created_at, updated_at
FROM learner_progress_records WHERE record_type = 'vocabulary_progress';

DO $$
DECLARE
    source_count bigint;
    target_count bigint;
BEGIN
    SELECT count(*) INTO source_count FROM assessment_component_records;
    SELECT (SELECT count(*) FROM rubric_criteria)
         + (SELECT count(*) FROM classroom_quiz_questions)
         + (SELECT count(*) FROM course_lesson_flashcard_refs) INTO target_count;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'assessment component backfill mismatch: source %, target %', source_count, target_count;
    END IF;

    SELECT count(*) INTO source_count FROM user_auxiliary_records;
    SELECT (SELECT count(*) FROM teacher_credentials)
         + (SELECT count(*) FROM teacher_course_feedback)
         + (SELECT count(*) FROM teacher_performance_evaluations)
         + (SELECT count(*) FROM teacher_google_meet_connections)
         + (SELECT count(*) FROM teacher_professional_profiles)
         + (SELECT count(*) FROM learner_lesson_notes)
         + (SELECT count(*) FROM learner_lesson_review_flags) INTO target_count;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'user auxiliary backfill mismatch: source %, target %', source_count, target_count;
    END IF;

    SELECT count(*) INTO source_count FROM classroom_operation_records;
    SELECT (SELECT count(*) FROM enrollment_request_status_history)
         + (SELECT count(*) FROM classroom_proposal_members)
         + (SELECT count(*) FROM classroom_attendance_disputes)
         + (SELECT count(*) FROM classroom_gradebook_entries)
         + (SELECT count(*) FROM lark_meeting_participants) INTO target_count;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'classroom operation backfill mismatch: source %, target %', source_count, target_count;
    END IF;

    SELECT count(*) INTO source_count FROM classroom_financial_records;
    SELECT (SELECT count(*) FROM classroom_tuition_payment_proofs)
         + (SELECT count(*) FROM classroom_tuition_payments) INTO target_count;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'classroom financial backfill mismatch: source %, target %', source_count, target_count;
    END IF;

    SELECT count(*) INTO source_count FROM learner_progress_records;
    SELECT (SELECT count(*) FROM lesson_progress)
         + (SELECT count(*) FROM vocabulary_progress) INTO target_count;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'learner progress backfill mismatch: source %, target %', source_count, target_count;
    END IF;
END $$;

DO $$
DECLARE
    table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'rubric_criteria', 'classroom_quiz_questions', 'course_lesson_flashcard_refs',
        'teacher_credentials', 'teacher_course_feedback', 'teacher_performance_evaluations',
        'teacher_google_meet_connections', 'teacher_professional_profiles',
        'learner_lesson_notes', 'learner_lesson_review_flags',
        'enrollment_request_status_history', 'classroom_proposal_members',
        'classroom_attendance_disputes', 'classroom_gradebook_entries',
        'lark_meeting_participants', 'classroom_tuition_payment_proofs',
        'classroom_tuition_payments', 'lesson_progress', 'vocabulary_progress'
    ] LOOP
        EXECUTE format(
            'SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE((SELECT max(id) FROM %I), 1), EXISTS (SELECT 1 FROM %I))',
            table_name, 'id', table_name, table_name
        );
    END LOOP;
END $$;

