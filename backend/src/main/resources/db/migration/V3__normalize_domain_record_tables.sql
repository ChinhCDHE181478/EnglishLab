-- Split the legacy record-type tables back into domain-specific relational tables.
-- Flyway runs PostgreSQL migrations transactionally, so count mismatches roll back the whole change.

CREATE TABLE rubric_criteria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rubric_id bigint NOT NULL REFERENCES assessment_rubrics(id),
    name varchar(120) NOT NULL,
    weight integer NOT NULL,
    description varchar(500),
    band_descriptors text,
    display_order integer NOT NULL
);
INSERT INTO rubric_criteria (id, rubric_id, name, weight, description, band_descriptors, display_order)
SELECT id, rubric_id, name, weight, description, band_descriptors, display_order
FROM assessment_component_records WHERE record_type = 'rubric_criteria';

