-- ---------------------------------------------------------------------------
-- 8. Reconciliation (fail migration on mismatch)
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_tp bigint;
    v_cp bigint;
    v_ilc bigint;
    v_map bigint;
    v_units_src bigint;
    v_units_dst bigint;
    v_lessons_src bigint;
    v_lessons_dst bigint;
    v_refs_src bigint;
    v_refs_dst bigint;
    v_orphan_unit bigint;
    v_orphan_lesson bigint;
    v_orphan_ref bigint;
    v_bad_bank_type bigint;
    v_offering_missing bigint;
BEGIN
    SELECT COUNT(*) INTO v_tp FROM training_programs;
    SELECT COUNT(*) INTO v_cp FROM curriculum_programs;
    SELECT COUNT(*) INTO v_ilc FROM instructor_led_courses;
    SELECT COUNT(*) INTO v_map FROM instructor_led_course_id_map;
    SELECT COUNT(*) INTO v_units_src FROM curriculum_units;
    SELECT COUNT(*) INTO v_units_dst FROM course_units;
    SELECT COUNT(*) INTO v_lessons_src FROM curriculum_session_plans;
    SELECT COUNT(*) INTO v_lessons_dst FROM course_lessons;
    SELECT COUNT(*) INTO v_refs_src FROM curriculum_resource_refs;
    SELECT COUNT(*) INTO v_refs_dst FROM course_unit_content_refs;

    IF v_tp <> v_cp OR v_ilc <> v_tp OR v_map <> (v_tp + v_cp) THEN
        RAISE EXCEPTION
            'Slice 5 ILC count mismatch: tp=%, cp=%, ilc=%, map=%',
            v_tp, v_cp, v_ilc, v_map;
    END IF;
    IF v_units_src <> v_units_dst THEN
        RAISE EXCEPTION 'Slice 5 unit count mismatch: src=%, dst=%', v_units_src, v_units_dst;
    END IF;
    IF v_lessons_src <> v_lessons_dst THEN
        RAISE EXCEPTION 'Slice 5 lesson count mismatch: src=%, dst=%', v_lessons_src, v_lessons_dst;
    END IF;
    IF v_refs_src <> v_refs_dst THEN
        RAISE EXCEPTION 'Slice 5 content-ref count mismatch: src=%, dst=%', v_refs_src, v_refs_dst;
    END IF;

    SELECT COUNT(*) INTO v_orphan_unit
    FROM course_units u
    LEFT JOIN instructor_led_courses c ON c.id = u.instructor_led_course_id
    WHERE c.id IS NULL;

    SELECT COUNT(*) INTO v_orphan_lesson
    FROM course_lessons l
    LEFT JOIN course_units u ON u.id = l.course_unit_id
    WHERE u.id IS NULL;

    SELECT COUNT(*) INTO v_orphan_ref
    FROM course_unit_content_refs r
    LEFT JOIN course_units u ON u.id = r.course_unit_id
    WHERE u.id IS NULL;

    IF v_orphan_unit > 0 OR v_orphan_lesson > 0 OR v_orphan_ref > 0 THEN
        RAISE EXCEPTION
            'Slice 5 orphan FKs: units=%, lessons=%, refs=%',
            v_orphan_unit, v_orphan_lesson, v_orphan_ref;
    END IF;

    SELECT COUNT(*) INTO v_bad_bank_type
    FROM course_unit_content_refs r
    JOIN content_bank_items b ON b.id = r.content_bank_item_id
    WHERE (r.content_type = 'EXERCISE' AND b.bank_type <> 'EXERCISE')
       OR (r.content_type = 'ASSESSMENT' AND b.bank_type <> 'ASSESSMENT')
       OR (r.content_type = 'FLASHCARD' AND b.bank_type <> 'FLASHCARD');

    IF v_bad_bank_type > 0 THEN
        RAISE EXCEPTION 'Slice 5 content_bank_item bank_type mismatch: %', v_bad_bank_type;
    END IF;

    SELECT COUNT(*) INTO v_offering_missing
    FROM classroom_offerings
    WHERE training_program_id IS NOT NULL
      AND instructor_led_course_id IS NULL;

    IF v_offering_missing > 0 THEN
        RAISE EXCEPTION
            'Slice 5 offerings missing instructor_led_course_id: %',
            v_offering_missing;
    END IF;
END $$;
