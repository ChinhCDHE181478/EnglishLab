WHERE s.curriculum_session_plan_id IS NOT NULL
  AND s.course_lesson_id IS NULL
  AND EXISTS (SELECT 1 FROM course_lessons cl WHERE cl.id = s.curriculum_session_plan_id);

ALTER TABLE classroom_homework
