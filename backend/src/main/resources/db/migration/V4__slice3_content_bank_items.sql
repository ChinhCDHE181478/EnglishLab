-- Slice 3: Content Bank unification into content_bank_items (Revision 4.2).
-- KEEP legacy bank tables until Slice 10. Typed ID map is required (legacy IDs collide).
-- status vs active: BOTH kept — AssessmentBankItem already uses both as distinct concepts;
--   types with only one field derive the other during backfill.

CREATE TABLE IF NOT EXISTS content_bank_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_type varchar(30) NOT NULL,
    code varchar(120),
    title varchar(220) NOT NULL,
    description text,
    exam_category varchar(40),
    skill varchar(60),
    status varchar(30) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    display_order integer NOT NULL DEFAULT 0,
    tags varchar(500),
    payload_jsonb jsonb NOT NULL DEFAULT '{}'::jsonb,
    rubric_bank_item_id bigint,
    created_by_id bigint REFERENCES users(id),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT content_bank_items_bank_type_check CHECK (
        bank_type IN ('ASSESSMENT', 'EXERCISE', 'RUBRIC', 'FLASHCARD', 'PLACEMENT_TEST')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_content_bank_items_code
    ON content_bank_items (code)
    WHERE code IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_content_bank_items_type ON content_bank_items (bank_type);
CREATE INDEX IF NOT EXISTS idx_content_bank_items_status ON content_bank_items (status);

CREATE TABLE IF NOT EXISTS content_bank_legacy_id_map (
    legacy_type varchar(30) NOT NULL,
    legacy_id bigint NOT NULL,
    content_bank_item_id bigint NOT NULL REFERENCES content_bank_items(id),
    PRIMARY KEY (legacy_type, legacy_id),
    CONSTRAINT content_bank_legacy_id_map_type_check CHECK (
        legacy_type IN ('ASSESSMENT', 'EXERCISE', 'RUBRIC', 'FLASHCARD', 'PLACEMENT_TEST')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_content_bank_legacy_map_target
    ON content_bank_legacy_id_map (content_bank_item_id);

