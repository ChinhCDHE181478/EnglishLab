-- ---------------------------------------------------------------------------
-- 7. Reconciliation
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    legacy_a bigint; bank_a bigint;
    legacy_e bigint; bank_e bigint;
    legacy_r bigint; bank_r bigint;
    legacy_f bigint; bank_f bigint;
    legacy_p bigint; bank_p bigint;
    map_dup bigint;
    bad_rubric bigint;
    bad_flash bigint;
    bad_place bigint;
    orphan_map bigint;
BEGIN
    SELECT count(*) INTO legacy_a FROM assessment_bank_items;
    SELECT count(*) INTO bank_a FROM content_bank_items WHERE bank_type = 'ASSESSMENT';
    IF legacy_a <> bank_a THEN
        RAISE EXCEPTION 'Slice3 A failed: assessment legacy=% bank=%', legacy_a, bank_a;
    END IF;

    SELECT count(*) INTO legacy_e FROM exercise_bank_items;
    SELECT count(*) INTO bank_e FROM content_bank_items WHERE bank_type = 'EXERCISE';
    IF legacy_e <> bank_e THEN
        RAISE EXCEPTION 'Slice3 B failed: exercise legacy=% bank=%', legacy_e, bank_e;
    END IF;

    SELECT count(*) INTO legacy_r FROM assessment_rubrics;
    SELECT count(*) INTO bank_r FROM content_bank_items WHERE bank_type = 'RUBRIC';
    IF legacy_r <> bank_r THEN
        RAISE EXCEPTION 'Slice3 C failed: rubric legacy=% bank=%', legacy_r, bank_r;
    END IF;

    SELECT count(*) INTO legacy_f FROM flashcard_sets;
    SELECT count(*) INTO bank_f FROM content_bank_items WHERE bank_type = 'FLASHCARD';
    IF legacy_f <> bank_f THEN
        RAISE EXCEPTION 'Slice3 D failed: flashcard legacy=% bank=%', legacy_f, bank_f;
    END IF;

    SELECT count(*) INTO legacy_p FROM placement_test_definitions;
    SELECT count(*) INTO bank_p FROM content_bank_items WHERE bank_type = 'PLACEMENT_TEST';
    IF legacy_p <> bank_p THEN
        RAISE EXCEPTION 'Slice3 E failed: placement legacy=% bank=%', legacy_p, bank_p;
    END IF;

    IF (legacy_a + legacy_e + legacy_r + legacy_f + legacy_p)
       <> (SELECT count(*) FROM content_bank_items) THEN
        RAISE EXCEPTION 'Slice3 F failed: total mismatch';
    END IF;

    SELECT count(*) INTO map_dup FROM (
        SELECT legacy_type, legacy_id FROM content_bank_legacy_id_map
        GROUP BY 1,2 HAVING count(*) > 1
    ) d;
    IF map_dup <> 0 THEN
        RAISE EXCEPTION 'Slice3 G failed: duplicate typed keys';
    END IF;

    IF (SELECT count(*) FROM content_bank_legacy_id_map)
       <> (SELECT count(*) FROM content_bank_items) THEN
        RAISE EXCEPTION 'Slice3 H failed: map size != bank size';
    END IF;

    SELECT count(*) INTO bad_rubric
    FROM content_bank_items a
    JOIN content_bank_items r ON r.id = a.rubric_bank_item_id
    WHERE a.rubric_bank_item_id IS NOT NULL
      AND (a.bank_type <> 'ASSESSMENT' OR r.bank_type <> 'RUBRIC');
    IF bad_rubric <> 0 THEN
        RAISE EXCEPTION 'Slice3 I failed: bad rubric_bank_item_id refs=%', bad_rubric;
    END IF;

    SELECT count(*) INTO bad_flash
    FROM online_lesson_flashcard_refs r
    JOIN content_bank_items c ON c.id = r.content_bank_item_id
    WHERE c.bank_type <> 'FLASHCARD';
    IF bad_flash <> 0 THEN
        RAISE EXCEPTION 'Slice3 J failed: flashcard refs wrong type=%', bad_flash;
    END IF;

    SELECT count(*) INTO bad_place
    FROM placement_test_attempts a
    JOIN content_bank_items c ON c.id = a.content_bank_item_id
    WHERE a.content_bank_item_id IS NOT NULL AND c.bank_type <> 'PLACEMENT_TEST';
    IF bad_place <> 0 THEN
        RAISE EXCEPTION 'Slice3 K failed: placement attempts wrong type=%', bad_place;
    END IF;

    SELECT count(*) INTO orphan_map
    FROM content_bank_legacy_id_map m
    WHERE NOT EXISTS (SELECT 1 FROM content_bank_items c WHERE c.id = m.content_bank_item_id);
    IF orphan_map <> 0 THEN
        RAISE EXCEPTION 'Slice3 L failed: orphan map rows=%', orphan_map;
    END IF;
END $$;
