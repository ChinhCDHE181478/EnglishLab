INSERT INTO content_bank_items (
    bank_type, code, title, description, exam_category, skill, status, active,
    display_order, tags, payload_jsonb, rubric_bank_item_id, created_by_id, created_at, updated_at
)
SELECT
    'RUBRIC',
    NULL,
    r.name,
    r.description,
    r.exam_type,
    r.skill::text,
    CASE WHEN r.active THEN 'PUBLISHED' ELSE 'ARCHIVED' END,
    r.active,
    0,
    NULL,
    jsonb_build_object(
        'taskType', r.task_type,
        'scoringScale', r.scoring_scale,
        'criteria', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'name', c.name,
                    'weight', c.weight,
                    'description', c.description,
                    'bandDescriptors', c.band_descriptors,
                    'displayOrder', c.display_order
                ) ORDER BY c.display_order NULLS LAST, c.id
            )
            FROM assessment_component_records c
            WHERE c.record_type = 'rubric_criteria'
              AND c.rubric_id = r.id
        ), '[]'::jsonb)
    ),
    NULL,
    NULL,
    NOW(),
    NOW()
FROM assessment_rubrics r
ORDER BY r.id;

WITH ordered_legacy AS (
    SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS rn FROM assessment_rubrics
),
ordered_bank AS (
    SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS rn
    FROM content_bank_items WHERE bank_type = 'RUBRIC'
)
INSERT INTO content_bank_legacy_id_map (legacy_type, legacy_id, content_bank_item_id)
SELECT 'RUBRIC', l.id, b.id
FROM ordered_legacy l
JOIN ordered_bank b ON b.rn = l.rn;

