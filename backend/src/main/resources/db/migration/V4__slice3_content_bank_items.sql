INSERT INTO content_bank_items (
    bank_type, code, title, description, exam_category, skill, status, active,
    display_order, tags, payload_jsonb, created_at, updated_at
)
SELECT
    'FLASHCARD',
    NULL,
    f.title,
    f.description,
    f.exam_category,
    f.skill,
    COALESCE(NULLIF(f.status, ''), 'DRAFT'),
    CASE WHEN COALESCE(f.status, 'DRAFT') IN ('ARCHIVED', 'INACTIVE') THEN false ELSE true END,
    COALESCE(f.display_order, 0),
    f.tags,
    jsonb_build_object(
        'cards', CASE
            WHEN f.cards_json IS NULL OR btrim(f.cards_json) = '' THEN '[]'::jsonb
            WHEN left(btrim(f.cards_json), 1) IN ('[', '{') THEN
                CASE WHEN f.cards_json::text ~ '^\s*[\[{]' THEN
                    COALESCE(f.cards_json::jsonb, '[]'::jsonb)
                ELSE jsonb_build_array(f.cards_json)
                END
            ELSE jsonb_build_array(f.cards_json)
        END
    ),
    f.created_at,
    f.updated_at
FROM flashcard_sets f
ORDER BY f.id;

WITH ordered_legacy AS (
    SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS rn FROM flashcard_sets
